#!/usr/bin/env python3
"""python3 -m unittest tools/test_known_ours.py"""
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import known_ours as k  # noqa: E402

SNIPPET = '''
            PackRow("K", "D", "u", new[] { "jh-x", "ublamf - y" },
                    new[] { "m" }, null, 1L << 10),
'''


class KnownOurs(unittest.TestCase):
    def test_packrow_stems_give_old_and_ios_names(self):
        names = k.table_names(SNIPPET)
        for n in ("jh-x.dfmod", "jh-x-ios.dfmod", "ublamf - y.dfmod", "ublamf-y-ios.dfmod"):
            self.assertIn(n, names)

    def test_collect_adds_the_ios_alias_at_the_same_size(self):
        d = tempfile.mkdtemp()
        with open(os.path.join(d, "jh-x.dfmod"), "wb") as f:
            f.write(b"0123456789")
        with open(os.path.join(d, "other.dfmod"), "wb") as f:
            f.write(b"01")
        found = k.collect([d], k.table_names(SNIPPET))
        self.assertEqual(found, [("jh-x-ios.dfmod", 10), ("jh-x.dfmod", 10)])

    def test_render_has_generated_header(self):
        self.assertTrue(k.render([("a.dfmod", 1)]).startswith("// GENERATED by tools/known_ours.py"))

    def test_frozen_v020_folder_is_a_default_source(self):
        self.assertIn("/Volumes/More data/AI projects/Daggerfall/release/v0.2.0/mitpack-dl/Mods", k.DEFAULT_DIRS)


if __name__ == "__main__":
    unittest.main()
