#!/usr/bin/env python3
"""Regenerate Assets/Scripts/Game/Mobile/MobileOriginalModsKnownOursLoose.cs.

KnownOursLoose = (leaf name lower-case, exact byte size, unlock key) of every LOOSE file we ship for a Non-MIT
mod: the DREAM music (.ogg -> Documents/Sound), movies (.mp4 + Daedra .FLC -> Documents/Movies) and extras
(SpellIcons atlases + metadata, settings Presets). MobileOriginalMods.IsLooseLocked treats a loose file that
matches one of these by name AND size as absent until the key's original has a receipt, so the player's own
files (other names, or the same name at another size) are never touched. Read-only; names and sizes come
from the zip directory, nothing is extracted.

Usage: python3 tools/known_ours_loose.py [--check] [ZIP ...]
  ZIPs default to the three DREAM loose-file zips below (all keyed DREAM).
  --check exits 1 when the generated file would change.
"""
import os
import sys
import zipfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CS_OUT = os.path.join(REPO, "Assets/Scripts/Game/Mobile/MobileOriginalModsKnownOursLoose.cs")
DREAM_DIR = "/Volumes/More data/AI projects/Daggerfall/dfu-mods/dream-ios-draft"
DEFAULT_ZIPS = [os.path.join(DREAM_DIR, n) for n in
                ("DREAM-music-ios.zip", "DREAM-movies-ios.zip", "DREAM-extras-ios.zip")]
KEY = "DREAM"


def entries(zip_path, key=KEY):
    """{(leaf lower-case, size, key)} of the files in one zip; folders and README* notes are skipped."""
    out = set()
    with zipfile.ZipFile(zip_path) as z:
        for info in z.infolist():
            if info.is_dir():
                continue
            leaf = info.filename.replace("\\", "/").rsplit("/", 1)[-1]
            if not leaf or leaf.lower().startswith("readme"):
                continue
            out.add((leaf.lower(), info.file_size, key))
    return out


def collect(zips):
    found = set()
    for z in zips:
        found |= entries(z)
    return sorted(found)


def render(rows):
    lines = [
        "// GENERATED by tools/known_ours_loose.py - do not edit by hand; rerun the script after rebuilding the DREAM loose-file zips.",
        "",
        "namespace DaggerfallWorkshop.Game.Mobile",
        "{",
        "    public static partial class MobileOriginalMods",
        "    {",
        "        /// <summary>(leaf name lower-case, exact size, unlock key) of every loose file we ship for a Non-MIT mod.</summary>",
        "        public static readonly LooseFile[] KnownOursLoose =",
        "        {",
    ]
    for name, size, key in rows:
        lines.append('            new LooseFile("%s", %dL, "%s"),' % (name.replace("\\", "\\\\").replace('"', '\\"'), size, key))
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    zips = [a for a in argv if a != "--check"] or DEFAULT_ZIPS
    missing = [z for z in zips if not os.path.isfile(z)]
    if missing:
        print("missing zip(s): " + ", ".join(missing))
        return 2
    text = render(collect(zips))
    old = open(CS_OUT, encoding="utf-8").read() if os.path.exists(CS_OUT) else None
    if check:
        return 0 if old == text else 1
    if old != text:
        with open(CS_OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("%d entries -> %s" % (text.count("new LooseFile("), os.path.relpath(CS_OUT, REPO)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
