#!/usr/bin/env python3
"""Regenerate Assets/Scripts/Game/Mobile/MobileOriginalModsKnownOurs.cs.

KnownOurs = (leaf name lower-case, exact byte size) of every pack .dfmod we have built whose name is an
OldNames or Unlocks entry of some recognizer row in MobileOriginalMods.cs. ScanOnce never treats such a file
as a desktop original (our old-name files carry UnityFS and pass the size floor, so they would self-unlock).
Every file found also adds its "-ios" alias at the same size (when that alias is a table name): a renamed copy of
our own bundle is still ours. Sources include the frozen release/v0.2.0/mitpack-dl/Mods folder (the exact bytes of
the v0.2.0 MIT zip); Assets/StreamingAssets/Mods is NOT a source (builtin app builds change it).

Usage: python3 tools/known_ours.py [--check] [DIR ...]
  DIRs default to the folders below; each is read at the top level only, read-only.
  --check exits 1 when the generated file would change.
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CS_TABLE = os.path.join(REPO, "Assets/Scripts/Game/Mobile/MobileOriginalMods.cs")
CS_OUT = os.path.join(REPO, "Assets/Scripts/Game/Mobile/MobileOriginalModsKnownOurs.cs")
HOME = os.path.expanduser("~")
DEFAULT_DIRS = [
    os.path.join(HOME, "dev/dfu-mods/astc-backup-20260915-weather2"),
    "/Volumes/More data/AI projects/Daggerfall/dfu-mods/dream-ios-draft",
    os.path.join(HOME, "dev/dfu-mods/dream-ios-draft"),
    os.path.join(HOME, "dev/dfu-mods"),
    os.path.join(HOME, "dev/dfu-mods/iOS"),
    "/Volumes/More data/AI projects/Daggerfall/release/v0.2.0/mitpack-dl/Mods",
]


def ios_name(stem):
    """Mirror of MobileOriginalMods.IosName / pack.py ios_name."""
    s = stem.lower()
    if s.endswith(".dfmod"):
        s = s[:-6]
    s = s.replace(" & ", " ").replace(" - ", "-").replace(" (", "_").replace(" of ", "_of_").replace(")", "")
    s = s.replace(" ", "-")
    if not s.endswith("-ios"):
        s += "-ios"
    return s + ".dfmod"


def table_names(cs_text):
    """Every OldNames/Unlocks leaf name of the C# recognizer table (lower-case)."""
    names = set()
    m = re.search(r"DreamPackStems\s*=\s*\{(.*?)\};", cs_text, re.S)
    for stem in re.findall(r'"([^"]+)"', m.group(1)) if m else []:
        names.add(stem.lower() + ".dfmod")
        names.add(ios_name(stem))
    for stem in re.findall(r'StemRow\(\s*"[^"]*",\s*"[^"]*",\s*"[^"]*",\s*"([^"]+)"', cs_text, re.S):
        names.add(stem.lower() + ".dfmod")
        names.add(ios_name(stem))
    for lit in re.findall(r'PackRow\(\s*"[^"]*",\s*"[^"]*",\s*"[^"]*",\s*new\[\]\s*\{([^}]*)\}', cs_text, re.S):
        for stem in re.findall(r'"([^"]+)"', lit):
            names.add(stem.lower() + ".dfmod")
            names.add(ios_name(stem))
    for extra in re.findall(r'WithOldNames\(StemRow\(.*?\)\s*,\s*((?:"[^"]+"\s*,?\s*)+)\)', cs_text, re.S):
        for n in re.findall(r'"([^"]+)"', extra):
            names.add(n.lower())
    for lit in re.findall(r'(?:Unlocks|OldNames)\s*=\s*(?:Concat\(\w+,\s*)?new\[\]\s*\{([^}]*)\}', cs_text):
        for n in re.findall(r'"([^"]+)"', lit):
            names.add(n.lower())
    return names


def collect(dirs, allowed):
    found = set()
    for d in dirs:
        if not os.path.isdir(d):
            continue
        for leaf in os.listdir(d):
            p = os.path.join(d, leaf)
            low = leaf.lower()
            if low.endswith(".dfmod") and low in allowed and os.path.isfile(p):
                size = os.path.getsize(p)
                found.add((low, size))
                if ios_name(low) in allowed:
                    found.add((ios_name(low), size))
    return sorted(found)


def render(pairs):
    lines = [
        "// GENERATED by tools/known_ours.py - do not edit by hand; rerun the script after building new pack files.",
        "using System.Collections.Generic;",
        "",
        "namespace DaggerfallWorkshop.Game.Mobile",
        "{",
        "    public static partial class MobileOriginalMods",
        "    {",
        "        /// <summary>(leaf name lower-case, exact size) of every pack .dfmod we built; never a desktop original.</summary>",
        "        public static readonly KeyValuePair<string, long>[] KnownOurs =",
        "        {",
    ]
    for name, size in pairs:
        lines.append('            new KeyValuePair<string, long>("%s", %dL),' % (name, size))
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    dirs = [a for a in argv if a != "--check"] or DEFAULT_DIRS
    with open(CS_TABLE, encoding="utf-8") as f:
        allowed = table_names(f.read())
    text = render(collect(dirs, allowed))
    old = open(CS_OUT, encoding="utf-8").read() if os.path.exists(CS_OUT) else None
    if check:
        return 0 if old == text else 1
    if old != text:
        with open(CS_OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("%d entries -> %s" % (text.count("new KeyValuePair"), os.path.relpath(CS_OUT, REPO)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
